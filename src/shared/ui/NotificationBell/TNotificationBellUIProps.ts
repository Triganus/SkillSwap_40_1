/**
 * Пропсы для компонента NotificationBellUI
 *
 * @property count - Количество непрочитанных уведомлений.
 *                   Если передан и больше 0, отображается красный бейдж с числом.
 *                   Если больше 9, отображается "9+".
 *                   Если не передан или равен 0, бейдж скрыт.
 *
 * @property onClick - Обработчик клика по колокольчику.
 *                     Опциональный, компонент может работать без него.
 */
export interface TNotificationBellUIProps {
  count?: number;
  onClick?: () => void;
}
